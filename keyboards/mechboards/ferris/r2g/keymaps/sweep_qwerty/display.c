// Replaces the Mechboards LCD UI with something plain enough for the office, in a quiet dark theme (GROUND, INK
// and the rest from screen_data.h).  Each half shows:
//   header - the layer's name over a thin accent line, and the names of the tools (Aero, tmux, nvim, Chrome,
//            Jupyter) whose keys are colour-coded on this layer, in their colours; "locked" instead while layer
//            lock holds the layer (there isn't room for both)
//   legend - that half's 17 keys on the current layer, laid out as on the board
//   status - Cmd Opt Ctrl Shift and Caps (Caps Word or Caps Lock), in the order the hand holds them
// The legends, cell positions and fonts are generated by sweep-layouts (screens.py) into screen_data.h and fonts/.

#include QMK_KEYBOARD_H
#include "transactions.h"
#include "common/display_lcd.h"
#include "screen_data.h"
#include "fonts/screen_big.qff.h"
#include "fonts/screen_mid.qff.h"
#include "fonts/screen_small.qff.h"
#include "fonts/screen_cap.qff.h"
#include "fonts/screen_title.qff.h"

#define LCD_W 135
#define LCD_H 240
#define LCD_OFFSET_X 52
#define LCD_OFFSET_Y 40

#define TICK_MS 30
#define STATUS_SYNC_MS 500
#define BACKLIGHT_DIM_MS 300000
#define BACKLIGHT_DIM_LEVEL 1

static painter_font_handle_t fonts[SCREEN_FONTS];

//----------------------------------------------------------
// Drawing helpers

static void fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, hsv_t c) {
    qp_rect(surface, x, y, x + w - 1, y + h - 1, c.h, c.s, c.v, true);
}

static void outline_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, hsv_t c, uint8_t thickness) {
    for (uint8_t i = 0; i < thickness; i++) {
        qp_rect(surface, x + i, y + i, x + w - 1 - i, y + h - 1 - i, c.h, c.s, c.v, false);
    }
}

static void text_centered(uint16_t x, uint16_t y, uint16_t w, uint8_t font, const char *str, hsv_t fg, hsv_t bg) {
    int16_t tw = qp_textwidth(fonts[font], str);
    qp_drawtext_recolor(surface, x + (w - tw) / 2, y, fonts[font], str, fg.h, fg.s, fg.v, bg.h, bg.s, bg.v);
}

//----------------------------------------------------------
// State.  The half without USB gets layers, mods and Caps Lock from QMK's split sync; Caps Word and layer
// lock come over in a status packet of our own.

typedef struct {
    bool          caps_word;
    layer_state_t locked;
} status_t;

static status_t remote_status;

static void status_rpc(uint8_t in_len, const void *in_data, uint8_t out_len, void *out_data) {
    if (in_len == sizeof(status_t)) memcpy(&remote_status, in_data, sizeof(status_t));
}

static status_t local_status(void) {
    if (!is_keyboard_master()) return remote_status;
    status_t st = {.caps_word = is_caps_word_on()};
    for (uint8_t i = 0; i < MAX_LAYER; i++) {
        if (is_layer_locked(i)) st.locked |= (layer_state_t)1 << i;
    }
    return st;
}

static void sync_status(void) {
    static status_t sent;
    static uint32_t last_sync;
    if (!is_keyboard_master()) return;
    status_t now = local_status();
    if (memcmp(&now, &sent, sizeof(now)) != 0 || timer_elapsed32(last_sync) > STATUS_SYNC_MS) {
        if (transaction_rpc_send(RPC_ID_SCREEN_STATUS, sizeof(now), &now)) {
            sent      = now;
            last_sync = timer_read32();
        }
    }
}

static uint8_t current_layer(void) {
    return get_highest_layer(layer_state | default_layer_state);
}

static hsv_t accent(uint8_t layer) {
    return layer < SCREEN_LAYERS ? screen_accents[layer] : MUTED;
}

//----------------------------------------------------------
// Header and legend: redrawn whenever the layer changes

// Right-aligned small text ending at x; returns where it starts.
static int16_t header_note(int16_t x, const char *str, hsv_t colour) {
    x -= qp_textwidth(fonts[FONT_CAP], str);
    qp_drawtext_recolor(surface, x, 9, fonts[FONT_CAP], str, colour.h, colour.s, colour.v, GROUND.h, GROUND.s, GROUND.v);
    return x;
}

static void draw_header(uint8_t layer, bool locked) {
    char buf[12];
    fill_rect(0, 0, LCD_W, SCREEN_HEADER_H - 2, GROUND);
    const char *title = layer < SCREEN_LAYERS ? screen_titles[layer] : buf;
    if (layer >= SCREEN_LAYERS) snprintf(buf, sizeof(buf), "Layer %u", layer);
    qp_drawtext_recolor(surface, 6, 5, fonts[FONT_TITLE], title, INK.h, INK.s, INK.v, GROUND.h, GROUND.s, GROUND.v);
    int16_t x = LCD_W - 5;
    if (locked) {
        header_note(x, "locked", accent(layer));
    } else if (layer < SCREEN_LAYERS) {
        for (uint8_t g = SCREEN_GROUPS - 1; g > 0; g--) {
            if (screen_layer_groups[layer] & (1 << g)) x = header_note(x, screen_group_names[g], screen_group_colours[g]) - 4;
        }
    }
    fill_rect(0, SCREEN_HEADER_H - 2, LCD_W, 2, accent(layer));
}

static void draw_key(const screen_cell_t *cell, const screen_key_t *key, hsv_t acc) {
    if (!key->main[0] && !key->held) {
        outline_rect(cell->x, cell->y, cell->w, cell->h, BLANK, 1);
        return;
    }
    hsv_t fill = KEY, edge = EDGE, ink = INK, sub = MUTED;
    bool  cap  = key->cap[0];
    if (key->held) {
        fill = edge = acc, ink = sub = ON_ACCENT;
    } else if (key->group) {    // a tool's key: its colour, as screens.py STYLE says
#if SCREEN_STYLE == SCREEN_STYLE_TINT
        fill = screen_group_tints[key->group], edge = screen_group_colours[key->group];
#elif SCREEN_STYLE == SCREEN_STYLE_TEXT
        ink = screen_group_colours[key->group];
#endif
    }
    fill_rect(cell->x, cell->y, cell->w, cell->h, fill);
    outline_rect(cell->x, cell->y, cell->w, cell->h, edge, 1);
#if SCREEN_STYLE == SCREEN_STYLE_BAR
    if (key->group && !key->held) fill_rect(cell->x + 3, cell->y + cell->h - 5, cell->w - 6, 3, screen_group_colours[key->group]);
#endif
    int16_t y = cell->y + (cell->h - fonts[key->font]->line_height) / 2 - (cap ? SCREEN_CAP_LIFT : 0);
    text_centered(cell->x, y, cell->w, key->font, key->main, ink, fill);
    if (cap) text_centered(cell->x, cell->y + cell->h - SCREEN_CAP_UP, cell->w, FONT_CAP, key->cap, sub, fill);
}

static void draw_legend(uint8_t layer) {
    fill_rect(0, SCREEN_HEADER_H, LCD_W, SCREEN_STATUS_Y - SCREEN_HEADER_H, GROUND);
    if (layer >= SCREEN_LAYERS) return;
    uint8_t side = is_keyboard_left() ? 0 : 1;
    for (uint8_t i = 0; i < SCREEN_KEYS; i++) {
        draw_key(&screen_cells[side][i], &screen_keys[layer][side][i], screen_accents[layer]);
    }
}

//----------------------------------------------------------
// Status strip: one tile per modifier, under the finger that holds it, and Caps under the inner column

enum tile_state { TILE_OFF, TILE_HELD, TILE_ONESHOT, TILE_LOCKED };

static const struct {
    uint8_t     mask;     // 0: Caps
    const char *glyph;
} tiles[5] = {{MOD_MASK_GUI, "⌘"}, {MOD_MASK_ALT, "⌥"}, {MOD_MASK_CTRL, "⌃"}, {MOD_MASK_SHIFT, "⇧"}, {0, "⇪"}};

static uint8_t tile_state(uint8_t i, const status_t *st) {
    uint8_t mask = tiles[i].mask;
    if (!mask) return st->caps_word || host_keyboard_led_state().caps_lock ? TILE_HELD : TILE_OFF;
    if (get_oneshot_locked_mods() & mask) return TILE_LOCKED;
    if (get_oneshot_mods() & mask) return TILE_ONESHOT;
    if (get_mods() & mask) return TILE_HELD;
    return TILE_OFF;
}

static void draw_tile(uint8_t i, uint8_t state, hsv_t acc) {
    uint8_t  slot = is_keyboard_left() ? i : 4 - i;           // mirrored on the right, like the hands
    uint16_t x = slot * SCREEN_PITCH_X, y = SCREEN_STATUS_Y, w = SCREEN_PITCH_X - 1, h = LCD_H - SCREEN_STATUS_Y - 4;
    hsv_t    fill = PANEL, ink = FAINT, border = EDGE;
    uint8_t  thickness = 1;
    switch (state) {
        case TILE_HELD:
            fill = acc, ink = ON_ACCENT, border = acc;
            break;
        case TILE_ONESHOT:
            ink = acc, border = acc, thickness = 2;
            break;
        case TILE_LOCKED:
            fill = INK, ink = ON_ACCENT, border = acc, thickness = 2;
            break;
    }
    fill_rect(x, y, w, h, fill);
    outline_rect(x, y, w, h, border, thickness);
    text_centered(x, y + (h - fonts[FONT_BIG]->line_height) / 2, w, FONT_BIG, tiles[i].glyph, ink, fill);
}

//----------------------------------------------------------
// LCD backlight dims when idle.  Runs on the master only; the level is split-synced to the other half and
// never written to EEPROM.

static void backlight_idle_task(void) {
    static bool    dimmed;
    static uint8_t saved_level;

    if (!is_keyboard_master()) return;

    bool idle = last_input_activity_elapsed() > BACKLIGHT_DIM_MS;
    if (idle && !dimmed && is_backlight_enabled() && get_backlight_level() > BACKLIGHT_DIM_LEVEL) {
        saved_level = get_backlight_level();
        dimmed      = true;
        backlight_level_noeeprom(BACKLIGHT_DIM_LEVEL);
    } else if (!idle && dimmed) {
        dimmed = false;
        backlight_level_noeeprom(saved_level);
    }
}

//----------------------------------------------------------
// Display hooks

static struct {
    uint8_t layer;
    bool    locked;
    uint8_t tiles[5];
} shown;

static void screen_task(bool force) {
    status_t st     = local_status();
    uint8_t  layer  = current_layer();
    bool     locked = (st.locked >> layer) & 1;
    if (force || layer != shown.layer || locked != shown.locked) {
        if (force || layer != shown.layer) draw_legend(layer);
        draw_header(layer, locked);
        shown.layer  = layer;
        shown.locked = locked;
        force        = true;    // the tiles take the layer's accent
    }
    for (uint8_t i = 0; i < 5; i++) {
        uint8_t state = tile_state(i, &st);
        if (force || state != shown.tiles[i]) {
            shown.tiles[i] = state;
            draw_tile(i, state, accent(layer));
        }
    }
}

static uint32_t display_tick(uint32_t trigger_time, void *cb_arg) {
    backlight_idle_task();
    sync_status();
    screen_task(false);
    qp_surface_draw(surface, lcd, LCD_OFFSET_X, LCD_OFFSET_Y, false);
    return TICK_MS;
}

// Returning false skips the keyboard's own splash, UI and display task.
bool display_init_user(void) {
    fonts[FONT_BIG]   = qp_load_font_mem(font_screen_big);
    fonts[FONT_MID]   = qp_load_font_mem(font_screen_mid);
    fonts[FONT_SMALL] = qp_load_font_mem(font_screen_small);
    fonts[FONT_CAP]   = qp_load_font_mem(font_screen_cap);
    fonts[FONT_TITLE] = qp_load_font_mem(font_screen_title);
    transaction_register_rpc(RPC_ID_SCREEN_STATUS, status_rpc);

    fill_rect(0, 0, LCD_W, LCD_H, GROUND);
    screen_task(true);
    qp_surface_draw(surface, lcd, LCD_OFFSET_X, LCD_OFFSET_Y, true);
    defer_exec(TICK_MS, display_tick, NULL);
    return false;
}
