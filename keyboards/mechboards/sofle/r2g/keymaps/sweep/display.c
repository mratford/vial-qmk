#define LCD_W 135
#define LCD_H 240
#define LCD_OFFSET_X 52
#define LCD_OFFSET_Y 40

#define TICK_MS 30
#define HAND_MAX_DOWN_MS 250
#define BLINK_MS 120
#define BLINK_MIN_GAP_MS 2000
#define BLINK_RAND_GAP_MS 4000
#define SLEEP_MS 30000
#define ZZZ_FRAME_MS 400
#define SWEAT_WPM_ON 50
#define SWEAT_WPM_OFF 45
#define BACKLIGHT_DIM_MS 300000
#define BACKLIGHT_DIM_LEVEL 1

static const hsv_t BLACK = {0, 0, 0};
static const hsv_t WHITE = {0, 0, 255};
static const hsv_t DIM   = {0, 0, 90};
static const hsv_t GREY  = {0, 0, 160};

//----------------------------------------------------------
// Layers. These mirror the Vial layout, so update them if layers move.

#include "layer_names.h"   // generated by sweep-layouts/build.py from the layer list

static const hsv_t layer_colours[] = {
    {129, 189, 220}, // BASE  teal
    {191, 170, 235}, // SYM   purple
    {85, 200, 220},  // NAV   green
    {21, 230, 245},  // MEDIA orange
    {36, 215, 245},  // NUM   gold
};

static uint8_t current_layer(void) {
    return get_highest_layer(layer_state | default_layer_state);
}

static hsv_t layer_colour(uint8_t layer) {
    return layer < ARRAY_SIZE(layer_colours) ? layer_colours[layer] : WHITE;
}

static void text_centered(uint16_t x, uint16_t y, uint16_t width, painter_font_handle_t font, const char *str, hsv_t fg, hsv_t bg) {
    int16_t text_width = qp_textwidth(font, str);
    qp_drawtext_recolor(surface, x + (width - text_width) / 2, y, font, str, fg.h, fg.s, fg.v, bg.h, bg.s, bg.v);
}

static void fill_rect(uint16_t left, uint16_t top, uint16_t right, uint16_t bottom, hsv_t colour) {
    qp_rect(surface, left, top, right, bottom, colour.h, colour.s, colour.v, true);
}

//----------------------------------------------------------
// Left screen: layer + modifiers

enum mod_tile_state { TILE_OFF, TILE_HELD, TILE_ONESHOT, TILE_LOCKED };

typedef struct {
    uint8_t     mask;
    const char *mac_label;
    const char *label;
    uint8_t     x;
    uint8_t     y;
} mod_tile_t;

#define TILE_W 62
#define TILE_H 52

// Laid out like the bottom-row home mods: GUI ALT / CTL SFT.
static const mod_tile_t mod_tiles[] = {
    {MOD_MASK_GUI, "CMD", "GUI", 3, 72},
    {MOD_MASK_ALT, "OPT", "ALT", 70, 72},
    {MOD_MASK_CTRL, "CTL", "CTL", 3, 129},
    {MOD_MASK_SHIFT, "SFT", "SFT", 70, 129},
};

#define FOOTER_Y 192
#define OS_Y 216

static struct {
    uint8_t layer;
    uint8_t tiles[ARRAY_SIZE(mod_tiles)];
    bool    mac;
    bool    caps;
    uint8_t wpm;
    uint8_t os;
} left_shown;

static bool host_is_mac(void) {
    os_variant_t os = detected_host_os();
    return os == OS_MACOS || os == OS_IOS;
}

static uint8_t mod_tile_state(uint8_t mask) {
    if (get_oneshot_locked_mods() & mask) return TILE_LOCKED;
    if (get_oneshot_mods() & mask) return TILE_ONESHOT;
    if (get_mods() & mask) return TILE_HELD;
    return TILE_OFF;
}

static bool caps_active(void) {
#ifdef CAPS_WORD_ENABLE
    if (is_caps_word_on()) return true;
#endif
    return host_keyboard_led_state().caps_lock;
}

static void draw_layer_header(uint8_t layer) {
    hsv_t accent = layer_colour(layer);
    char  buf[16];

    fill_rect(0, 0, LCD_W - 1, 66, BLACK);
    snprintf(buf, sizeof(buf), "LAYER %u", layer);
    text_centered(0, 4, LCD_W, pixellari_18, buf, GREY, BLACK);

    fill_rect(0, 28, LCD_W - 1, 62, accent);
    if (layer < ARRAY_SIZE(layer_names)) {
        snprintf(buf, sizeof(buf), "%s", layer_names[layer]);
    } else {
        snprintf(buf, sizeof(buf), "L%u", layer);
    }
    text_centered(0, 28 + (35 - pixellari_24->line_height) / 2, LCD_W, pixellari_24, buf, BLACK, accent);
}

static void draw_mod_tile(const mod_tile_t *tile, uint8_t state, hsv_t accent, bool mac) {
    uint16_t left = tile->x, top = tile->y;
    uint16_t right = left + TILE_W - 1, bottom = top + TILE_H - 1;
    hsv_t    fill, text, border;
    uint8_t  thickness;

    switch (state) {
        case TILE_HELD:
            fill = accent, text = BLACK, border = accent, thickness = 1;
            break;
        case TILE_ONESHOT:
            fill = BLACK, text = accent, border = accent, thickness = 3;
            break;
        case TILE_LOCKED:
            fill = WHITE, text = BLACK, border = accent, thickness = 3;
            break;
        default:
            fill = BLACK, text = DIM, border = DIM, thickness = 1;
            break;
    }

    fill_rect(left, top, right, bottom, fill);
    for (uint8_t i = 0; i < thickness; i++) {
        qp_rect(surface, left + i, top + i, right - i, bottom - i, border.h, border.s, border.v, false);
    }
    text_centered(left, top + (TILE_H - pixellari_24->line_height) / 2, TILE_W, pixellari_24, mac ? tile->mac_label : tile->label, text, fill);
    if (state == TILE_LOCKED) {
        fill_rect(left + 18, bottom - 10, right - 18, bottom - 8, BLACK);
    }
}

static void draw_caps(bool caps, hsv_t accent) {
    fill_rect(0, FOOTER_Y, LCD_W / 2 - 1, FOOTER_Y + pixellari_18->line_height, BLACK);
    text_centered(0, FOOTER_Y, LCD_W / 2, pixellari_18, "CAPS", caps ? accent : DIM, BLACK);
}

static void draw_left_wpm(uint8_t wpm) {
    char buf[12];
    snprintf(buf, sizeof(buf), "%u WPM", wpm);
    fill_rect(LCD_W / 2, FOOTER_Y, LCD_W - 1, FOOTER_Y + pixellari_18->line_height, BLACK);
    text_centered(LCD_W / 2, FOOTER_Y, LCD_W - LCD_W / 2, pixellari_18, buf, GREY, BLACK);
}

static void draw_os(os_variant_t os) {
    const char *name;
    switch (os) {
        case OS_MACOS:
            name = "macOS";
            break;
        case OS_IOS:
            name = "iOS";
            break;
        case OS_WINDOWS:
            name = "Windows";
            break;
        case OS_LINUX:
            name = "Linux";
            break;
        default:
            name = "";
            break;
    }
    fill_rect(0, OS_Y, LCD_W - 1, LCD_H - 1, BLACK);
    text_centered(0, OS_Y, LCD_W, pixellari_18, name, DIM, BLACK);
}

static void left_task(bool force) {
    uint8_t layer = current_layer();
    if (force || layer != left_shown.layer) {
        // Accent colour follows the layer, so repaint everything.
        if (force) fill_rect(0, 0, LCD_W - 1, LCD_H - 1, BLACK);
        left_shown.layer = layer;
        draw_layer_header(layer);
        force = true;
    }
    hsv_t accent = layer_colour(layer);

    bool mac = host_is_mac();
    if (mac != left_shown.mac) {
        left_shown.mac = mac;
        force          = true;
    }

    for (uint8_t i = 0; i < ARRAY_SIZE(mod_tiles); i++) {
        uint8_t state = mod_tile_state(mod_tiles[i].mask);
        if (force || state != left_shown.tiles[i]) {
            left_shown.tiles[i] = state;
            draw_mod_tile(&mod_tiles[i], state, accent, mac);
        }
    }

    bool caps = caps_active();
    if (force || caps != left_shown.caps) {
        left_shown.caps = caps;
        draw_caps(caps, accent);
    }

    uint8_t wpm = get_current_wpm();
    if (force || wpm != left_shown.wpm) {
        left_shown.wpm = wpm;
        draw_left_wpm(wpm);
    }

    os_variant_t os = detected_host_os();
    if (force || os != left_shown.os) {
        left_shown.os = os;
        draw_os(os);
    }
}

//----------------------------------------------------------
// Right screen: typing avatar

enum { HAND_LEFT, HAND_RIGHT, HAND_NONE };

static painter_image_handle_t img_base, img_hands[2][2], img_eyes[2], img_sweat[2], img_zzz_off, img_zzz[3];

static struct {
    uint32_t last_matrix;
    uint8_t  hand_down;
    uint8_t  next_hand;
    uint32_t hand_since;
    bool     eyes_closed;
    uint32_t next_blink;
    bool     asleep;
    uint8_t  zzz_frame;
    uint32_t next_zzz;
    bool     sweating;
    uint8_t  wpm;
} avatar;

static void load_avatar_images(void) {
    img_base             = qp_load_image_mem(gfx_scene_base);
    img_hands[0][false]  = qp_load_image_mem(gfx_hand_l_up);
    img_hands[0][true]   = qp_load_image_mem(gfx_hand_l_down);
    img_hands[1][false]  = qp_load_image_mem(gfx_hand_r_up);
    img_hands[1][true]   = qp_load_image_mem(gfx_hand_r_down);
    img_eyes[false]      = qp_load_image_mem(gfx_eyes_open);
    img_eyes[true]       = qp_load_image_mem(gfx_eyes_closed);
    img_sweat[false]     = qp_load_image_mem(gfx_sweat_off);
    img_sweat[true]      = qp_load_image_mem(gfx_sweat_on);
    img_zzz_off          = qp_load_image_mem(gfx_zzz_off);
    img_zzz[0]           = qp_load_image_mem(gfx_zzz_0);
    img_zzz[1]           = qp_load_image_mem(gfx_zzz_1);
    img_zzz[2]           = qp_load_image_mem(gfx_zzz_2);
}

static void draw_hand(uint8_t hand, bool down) {
    if (hand == HAND_LEFT) {
        qp_drawimage(surface, SCENE_HAND_L_X, SCENE_HAND_L_Y, img_hands[0][down]);
    } else {
        qp_drawimage(surface, SCENE_HAND_R_X, SCENE_HAND_R_Y, img_hands[1][down]);
    }
}

static void lift_hand(void) {
    if (avatar.hand_down != HAND_NONE) {
        draw_hand(avatar.hand_down, false);
        avatar.hand_down = HAND_NONE;
    }
}

static void set_eyes(bool closed) {
    avatar.eyes_closed = closed;
    qp_drawimage(surface, SCENE_EYES_X, SCENE_EYES_Y, img_eyes[closed]);
}

static void schedule_blink(uint32_t now) {
    avatar.next_blink = now + BLINK_MIN_GAP_MS + rand() % BLINK_RAND_GAP_MS;
}

static void draw_desk_wpm(uint8_t wpm) {
    static const hsv_t front = {SCENE_FRONT_HSV};
    static const hsv_t ink   = {28, 60, 220};
    char               buf[12];

    snprintf(buf, sizeof(buf), "%u WPM", wpm);
    fill_rect(0, SCENE_FRONT_Y, LCD_W - 1, LCD_H - 1, front);
    text_centered(0, SCENE_FRONT_Y + (LCD_H - SCENE_FRONT_Y - pixellari_18->line_height) / 2, LCD_W, pixellari_18, buf, ink, front);
}

static void right_init(void) {
    load_avatar_images();
    qp_drawimage(surface, 0, 0, img_base);

    uint32_t now       = timer_read32();
    avatar.last_matrix = last_matrix_activity_time();
    avatar.hand_down   = HAND_NONE;
    avatar.wpm         = get_current_wpm();
    schedule_blink(now);
    draw_desk_wpm(avatar.wpm);
}

static void right_task(void) {
    uint32_t now  = timer_read32();
    bool     idle = last_input_activity_elapsed() > SLEEP_MS;

    if (avatar.asleep && !idle) {
        avatar.asleep = false;
        qp_drawimage(surface, SCENE_ZZZ_X, SCENE_ZZZ_Y, img_zzz_off);
        set_eyes(false);
        schedule_blink(now);
    } else if (!avatar.asleep && idle) {
        avatar.asleep    = true;
        avatar.zzz_frame = 0;
        avatar.next_zzz  = now;
        lift_hand();
        set_eyes(true);
    }

    // Each matrix change is a press or a release: press puts the next hand
    // down, release lifts it. Held keys lift on a timeout instead.
    uint32_t matrix = last_matrix_activity_time();
    if (matrix != avatar.last_matrix) {
        avatar.last_matrix = matrix;
        if (avatar.hand_down == HAND_NONE) {
            avatar.hand_down  = avatar.next_hand;
            avatar.next_hand  = avatar.next_hand == HAND_LEFT ? HAND_RIGHT : HAND_LEFT;
            avatar.hand_since = now;
            draw_hand(avatar.hand_down, true);
        } else {
            lift_hand();
        }
    } else if (avatar.hand_down != HAND_NONE && timer_elapsed32(avatar.hand_since) > HAND_MAX_DOWN_MS) {
        lift_hand();
    }

    if (avatar.asleep) {
        if (timer_expired32(now, avatar.next_zzz)) {
            qp_drawimage(surface, SCENE_ZZZ_X, SCENE_ZZZ_Y, img_zzz[avatar.zzz_frame]);
            avatar.zzz_frame = (avatar.zzz_frame + 1) % ARRAY_SIZE(img_zzz);
            avatar.next_zzz  = now + ZZZ_FRAME_MS;
        }
    } else if (!avatar.eyes_closed && timer_expired32(now, avatar.next_blink)) {
        set_eyes(true);
        avatar.next_blink = now + BLINK_MS;
    } else if (avatar.eyes_closed && timer_expired32(now, avatar.next_blink)) {
        set_eyes(false);
        schedule_blink(now);
    }

    uint8_t wpm = get_current_wpm();
    if (!avatar.sweating && wpm > SWEAT_WPM_ON) {
        avatar.sweating = true;
        qp_drawimage(surface, SCENE_SWEAT_X, SCENE_SWEAT_Y, img_sweat[true]);
    } else if (avatar.sweating && wpm < SWEAT_WPM_OFF) {
        avatar.sweating = false;
        qp_drawimage(surface, SCENE_SWEAT_X, SCENE_SWEAT_Y, img_sweat[false]);
    }
    if (wpm != avatar.wpm) {
        avatar.wpm = wpm;
        draw_desk_wpm(wpm);
    }
}

//----------------------------------------------------------
// LCD backlight dims when idle. Runs on the master only; the level is
// split-synced to the other half and never written to EEPROM.

static void backlight_idle_task(void) {
    static bool    dimmed;
    static uint8_t saved_level;

    if (!is_keyboard_master()) return;

    bool idle = last_input_activity_elapsed() > BACKLIGHT_DIM_MS;
    if (idle && !dimmed && is_backlight_enabled() && get_backlight_level() > BACKLIGHT_DIM_LEVEL) {
        saved_level = get_backlight_level();
        dimmed      = true;
        backlight_level_noeeprom(BACKLIGHT_DIM_LEVEL);
    } else if (!idle && dimmed) {
        dimmed = false;
        backlight_level_noeeprom(saved_level);
    }
}

//----------------------------------------------------------
// Display hooks

static uint32_t display_tick(uint32_t trigger_time, void *cb_arg) {
    backlight_idle_task();
    if (is_keyboard_left()) {
        left_task(false);
    } else {
        right_task();
    }
    qp_surface_draw(surface, lcd, LCD_OFFSET_X, LCD_OFFSET_Y, false);
    return TICK_MS;
}

// Returning false skips the keyboard's own splash, UI and display task.
bool display_init_user(void) {
    if (is_keyboard_left()) {
        left_task(true);
    } else {
        right_init();
    }
    qp_surface_draw(surface, lcd, LCD_OFFSET_X, LCD_OFFSET_Y, true);
    defer_exec(TICK_MS, display_tick, NULL);
    return false;
}

//----------------------------------------------------------
// Underglow takes the layer colour off the base layer.

bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {
    uint8_t layer = current_layer();
    if (layer == 0) return true;

    hsv_t hsv = layer_colour(layer);
    hsv.v     = rgb_matrix_get_val();
    rgb_t rgb = hsv_to_rgb(hsv);
    for (uint8_t i = led_min; i < led_max; i++) {
        if (HAS_FLAGS(g_led_config.flags[i], LED_FLAG_UNDERGLOW)) {
            rgb_matrix_set_color(i, rgb.r, rgb.g, rgb.b);
        }
    }
    return true;
}
